namespace NativeUI.Controls;

/// <summary>
/// Specifies an edge of a container, following WPF's Dock enumeration.
/// </summary>
public enum Dock
{
    /// <summary>Positions content at the left edge.</summary>
    Left,
    /// <summary>Positions content at the top edge.</summary>
    Top,
    /// <summary>Positions content at the right edge.</summary>
    Right,
    /// <summary>Positions content at the bottom edge.</summary>
    Bottom
}
