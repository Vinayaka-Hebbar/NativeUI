using System.Globalization;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using static Microsoft.CodeAnalysis.CSharp.SyntaxFactory;

namespace NativeUI.Xaml.Compiler;

/// <summary>
/// Generates clean, human-readable partial C# initialization code from a <see cref="ValidatedXamlDocument"/>
/// using Roslyn's <see cref="SyntaxFactory"/>.
/// </summary>
public static class XamlEmitter
{
    /// <summary>
    /// Builds a Roslyn <see cref="CompilationUnitSyntax"/> for the compiled view class and formats it as C# source text.
    /// </summary>
    public static string Emit(
        ValidatedXamlDocument document,
        Accessibility accessibility = Accessibility.Public)
    {
        ArgumentNullException.ThrowIfNull(document);
        CompilationUnitSyntax? unit = BuildCompilationUnit(document, accessibility);
        return unit is null ? string.Empty : unit.NormalizeWhitespace().ToFullString();
    }

    /// <summary>
    /// Builds the Roslyn <see cref="CompilationUnitSyntax"/> for the given <paramref name="document"/>.
    /// </summary>
    public static CompilationUnitSyntax? BuildCompilationUnit(
        ValidatedXamlDocument document,
        Accessibility accessibility = Accessibility.Public)
    {
        ArgumentNullException.ThrowIfNull(document);
        if (document.RootElement is null)
        {
            return null;
        }

        List<MemberDeclarationSyntax> classMembers = [];

        // Emit auto-properties for x:Name elements
        List<(string Name, string ControlType)> namedElements = [];
        CollectNamedElements(document.RootElement, isRoot: true, namedElements);
        foreach ((string propName, string controlType) in namedElements)
        {
            classMembers.Add(BuildNamedElementProperty(propName, controlType));
        }

        classMembers.Add(BuildAttachStylesPartialMethod());
        classMembers.Add(BuildInitializeComponentMethod(document));

        AttributeListSyntax xamlCompilationAttr = AttributeList(SingletonSeparatedList(
            Attribute(IdentifierName("XamlCompilation"))
                .WithArgumentList(AttributeArgumentList(SingletonSeparatedList(
                    AttributeArgument(StringLiteral(Path.GetFileName(document.FilePath))))))));

        BaseTypeSyntax baseType = SimpleBaseType(IdentifierName(document.RootElement.ControlTypeName));

        SyntaxKind accessKeyword = accessibility == Accessibility.Internal
            ? SyntaxKind.InternalKeyword
            : SyntaxKind.PublicKeyword;

        ClassDeclarationSyntax classDecl = ClassDeclaration(document.ClassName)
            .WithAttributeLists(SingletonList(xamlCompilationAttr))
            .WithModifiers(TokenList(Token(accessKeyword), Token(SyntaxKind.PartialKeyword)))
            .WithBaseList(BaseList(SingletonSeparatedList(baseType)))
            .WithMembers(List(classMembers));

        FileScopedNamespaceDeclarationSyntax namespaceDecl =
            FileScopedNamespaceDeclaration(ParseName(document.NamespaceName))
                .WithMembers(SingletonList<MemberDeclarationSyntax>(classDecl));

        SyntaxTriviaList leadingTrivia = TriviaList(
            Comment("// <auto-generated />"),
            Trivia(NullableDirectiveTrivia(Token(SyntaxKind.EnableKeyword), true)),
            Trivia(PragmaWarningDirectiveTrivia(
                Token(SyntaxKind.DisableKeyword),
                SeparatedList<ExpressionSyntax>([IdentifierName("CS1591")]),
                true)));

        return CompilationUnit()
            .WithUsings(List(
            [
                UsingDirective(ParseName("NativeUI.Controls")),
                UsingDirective(ParseName("NativeUI.Core")),
                UsingDirective(ParseName("NativeUI.Layout")),
                UsingDirective(ParseName("NativeUI.Media")),
                UsingDirective(ParseName("NativeUI.Xaml"))
            ]))
            .WithMembers(SingletonList<MemberDeclarationSyntax>(namespaceDecl))
            .WithLeadingTrivia(leadingTrivia);
    }

    private static PropertyDeclarationSyntax BuildNamedElementProperty(string propName, string controlType)
    {
        TypeSyntax typeSyntax = IdentifierName(controlType);
        AccessorDeclarationSyntax getter = AccessorDeclaration(SyntaxKind.GetAccessorDeclaration)
            .WithSemicolonToken(Token(SyntaxKind.SemicolonToken));
        AccessorDeclarationSyntax privateSetter = AccessorDeclaration(SyntaxKind.SetAccessorDeclaration)
            .WithModifiers(TokenList(Token(SyntaxKind.PrivateKeyword)))
            .WithSemicolonToken(Token(SyntaxKind.SemicolonToken));

        PostfixUnaryExpressionSyntax nullBang = PostfixUnaryExpression(
            SyntaxKind.SuppressNullableWarningExpression,
            LiteralExpression(SyntaxKind.NullLiteralExpression));

        return PropertyDeclaration(typeSyntax, Identifier(propName))
            .WithModifiers(TokenList(Token(SyntaxKind.PublicKeyword)))
            .WithAccessorList(AccessorList(List([getter, privateSetter])))
            .WithInitializer(EqualsValueClause(nullBang))
            .WithSemicolonToken(Token(SyntaxKind.SemicolonToken));
    }

    private static MethodDeclarationSyntax BuildAttachStylesPartialMethod()
    {
        return MethodDeclaration(PredefinedType(Token(SyntaxKind.VoidKeyword)), Identifier("AttachStyles"))
            .WithModifiers(TokenList(Token(SyntaxKind.PartialKeyword)))
            .WithSemicolonToken(Token(SyntaxKind.SemicolonToken));
    }

    private static MethodDeclarationSyntax BuildInitializeComponentMethod(ValidatedXamlDocument document)
    {
        List<StatementSyntax> statements = [];

        ValidatedXamlElement root = document.RootElement!;
        EmitElementPropertyStatements(statements, ThisExpression(), root, document.DataType, document.NamespaceName);

        statements.Add(ExpressionStatement(InvocationExpression(IdentifierName("AttachStyles"))));

        int counter = 0;
        foreach (ValidatedXamlElement child in root.Children)
        {
            EmitChildElementStatements(statements, ThisExpression(), child, document.DataType, document.NamespaceName, ref counter);
        }

        return MethodDeclaration(PredefinedType(Token(SyntaxKind.VoidKeyword)), Identifier("InitializeComponent"))
            .WithModifiers(TokenList(Token(SyntaxKind.PublicKeyword)))
            .WithBody(Block(statements));
    }

    private static void CollectNamedElements(
        ValidatedXamlElement element,
        bool isRoot,
        List<(string Name, string ControlType)> results)
    {
        if (!isRoot && !string.IsNullOrWhiteSpace(element.XName))
        {
            results.Add((element.XName!, element.ControlTypeName));
        }

        foreach (ValidatedXamlElement child in element.Children)
        {
            CollectNamedElements(child, isRoot: false, results);
        }
    }

    private static void EmitChildElementStatements(
        List<StatementSyntax> statements,
        ExpressionSyntax parentExpr,
        ValidatedXamlElement element,
        string? dataType,
        string viewNamespace,
        ref int counter)
    {
        counter++;
        string varName = !string.IsNullOrWhiteSpace(element.XName)
            ? element.XName!
            : $"element{counter}";

        TypeSyntax controlType = IdentifierName(element.ControlTypeName);
        ObjectCreationExpressionSyntax newControl = ObjectCreationExpression(controlType)
            .WithArgumentList(ArgumentList());

        if (!string.IsNullOrWhiteSpace(element.XName))
        {
            statements.Add(ExpressionStatement(
                AssignmentExpression(
                    SyntaxKind.SimpleAssignmentExpression,
                    IdentifierName(varName),
                    newControl)));
        }
        else
        {
            statements.Add(LocalDeclarationStatement(
                VariableDeclaration(IdentifierName("var"))
                    .WithVariables(SingletonSeparatedList(
                        VariableDeclarator(Identifier(varName))
                            .WithInitializer(EqualsValueClause(newControl))))));
        }

        IdentifierNameSyntax currentVarExpr = IdentifierName(varName);
        EmitElementPropertyStatements(statements, currentVarExpr, element, dataType, viewNamespace);

        ExpressionSyntax childrenMember = parentExpr is ThisExpressionSyntax
            ? IdentifierName("Children")
            : MemberAccessExpression(
                SyntaxKind.SimpleMemberAccessExpression,
                parentExpr,
                IdentifierName("Children"));

        MemberAccessExpressionSyntax addMethod = MemberAccessExpression(
            SyntaxKind.SimpleMemberAccessExpression,
            childrenMember,
            IdentifierName("Add"));

        statements.Add(ExpressionStatement(
            InvocationExpression(addMethod)
                .WithArgumentList(ArgumentList(SingletonSeparatedList(Argument(currentVarExpr))))));

        foreach (ValidatedXamlElement grandChild in element.Children)
        {
            EmitChildElementStatements(statements, currentVarExpr, grandChild, dataType, viewNamespace, ref counter);
        }
    }

    private static void EmitElementPropertyStatements(
        List<StatementSyntax> statements,
        ExpressionSyntax targetExpr,
        ValidatedXamlElement element,
        string? dataType,
        string viewNamespace)
    {
        foreach (ValidatedXamlProperty prop in element.Properties)
        {
            if (prop.Binding is BindingExpressionNode binding)
            {
                statements.Add(BuildBindingStatement(targetExpr, element.ControlTypeName, prop.PropertyName, binding, dataType, viewNamespace));
            }
            else if (prop.LiteralValue is not null)
            {
                statements.Add(BuildLiteralAssignmentStatement(targetExpr, prop.PropertyName, prop.Kind, prop.LiteralValue));
            }
        }
    }

    private static ExpressionStatementSyntax BuildLiteralAssignmentStatement(
        ExpressionSyntax targetExpr,
        string propertyName,
        XamlPropertyKind kind,
        string rawLiteral)
    {
        if (kind == XamlPropertyKind.AttachedInt32)
        {
            return BuildAttachedSetterStatement(targetExpr, propertyName, rawLiteral);
        }

        if (kind == XamlPropertyKind.StyleThickness)
        {
            return BuildStyleThicknessStatement(targetExpr, propertyName, rawLiteral);
        }

        ExpressionSyntax targetMember = targetExpr is ThisExpressionSyntax
            ? IdentifierName(propertyName)
            : MemberAccessExpression(
                SyntaxKind.SimpleMemberAccessExpression,
                targetExpr,
                IdentifierName(propertyName));

        return ExpressionStatement(
            AssignmentExpression(SyntaxKind.SimpleAssignmentExpression, targetMember, BuildLiteralValue(kind, rawLiteral)));
    }

    /// <summary>
    /// Emits <c>Grid.SetRow(target, 1);</c> for the attribute <c>Grid.Row="1"</c>.
    /// </summary>
    private static ExpressionStatementSyntax BuildAttachedSetterStatement(ExpressionSyntax targetExpr, string propertyName, string rawLiteral)
    {
        string[] parts = propertyName.Split('.');
        MemberAccessExpressionSyntax setter = MemberAccessExpression(
            SyntaxKind.SimpleMemberAccessExpression,
            IdentifierName(parts[0]),
            IdentifierName($"Set{parts[1]}"));

        LiteralExpressionSyntax value = LiteralExpression(
            SyntaxKind.NumericLiteralExpression,
            Literal(int.Parse(rawLiteral, NumberStyles.None, CultureInfo.InvariantCulture)));

        return ExpressionStatement(
            InvocationExpression(setter)
                .WithArgumentList(ArgumentList(SeparatedList([Argument(targetExpr), Argument(value)]))));
    }

    /// <summary>
    /// Emits <c>(target.Style ??= new Style()).Margin = new Thickness(...);</c> for the attribute <c>Margin="..."</c>.
    /// </summary>
    private static ExpressionStatementSyntax BuildStyleThicknessStatement(ExpressionSyntax targetExpr, string propertyName, string rawLiteral)
    {
        ExpressionSyntax styleMember = targetExpr is ThisExpressionSyntax
            ? IdentifierName("Style")
            : MemberAccessExpression(SyntaxKind.SimpleMemberAccessExpression, targetExpr, IdentifierName("Style"));

        ExpressionSyntax style = ParenthesizedExpression(
            AssignmentExpression(
                SyntaxKind.CoalesceAssignmentExpression,
                styleMember,
                ObjectCreationExpression(IdentifierName("Style")).WithArgumentList(ArgumentList())));

        _ = XamlValidator.TryParseThickness(rawLiteral, out double[] values);
        ExpressionSyntax thickness = ObjectCreationExpression(IdentifierName("Thickness"))
            .WithArgumentList(ArgumentList(SeparatedList(values.Select(static value =>
                Argument(LiteralExpression(SyntaxKind.NumericLiteralExpression, Literal(value)))))));

        return ExpressionStatement(
            AssignmentExpression(
                SyntaxKind.SimpleAssignmentExpression,
                MemberAccessExpression(SyntaxKind.SimpleMemberAccessExpression, style, IdentifierName(propertyName)),
                thickness));
    }

    private static ExpressionSyntax BuildLiteralValue(XamlPropertyKind kind, string rawLiteral)
    {
        return kind switch
        {
            XamlPropertyKind.String => StringLiteral(rawLiteral),
            XamlPropertyKind.Boolean => bool.Parse(rawLiteral)
                ? LiteralExpression(SyntaxKind.TrueLiteralExpression)
                : LiteralExpression(SyntaxKind.FalseLiteralExpression),
            XamlPropertyKind.Int32 => LiteralExpression(
                SyntaxKind.NumericLiteralExpression,
                Literal(int.Parse(rawLiteral, NumberStyles.Integer, CultureInfo.InvariantCulture))),
            XamlPropertyKind.Int64 => LiteralExpression(
                SyntaxKind.NumericLiteralExpression,
                Literal(long.Parse(rawLiteral, NumberStyles.Integer, CultureInfo.InvariantCulture))),
            XamlPropertyKind.Double => LiteralExpression(
                SyntaxKind.NumericLiteralExpression,
                Literal(double.Parse(rawLiteral, NumberStyles.Float, CultureInfo.InvariantCulture))),
            XamlPropertyKind.Orientation => MemberAccessExpression(
                SyntaxKind.SimpleMemberAccessExpression,
                IdentifierName("Orientation"),
                IdentifierName(rawLiteral)),
            XamlPropertyKind.GridLengthList => CollectionExpression(SeparatedList<CollectionElementSyntax>(
                XamlValidator.SplitList(rawLiteral).Select(static token => ExpressionElement(StringLiteral(token))))),
            XamlPropertyKind.ClassList => CollectionExpression(SeparatedList<CollectionElementSyntax>(
                XamlValidator.SplitClassNames(rawLiteral).Select(static name => ExpressionElement(StringLiteral(name))))),
            _ => throw new ArgumentOutOfRangeException(nameof(kind), kind, "The property kind has no literal form.")
        };
    }

    private static ExpressionStatementSyntax BuildBindingStatement(
        ExpressionSyntax targetExpr,
        string controlTypeName,
        string propertyName,
        BindingExpressionNode binding,
        string? dataType,
        string viewNamespace)
    {
        ExpressionSyntax propertyDescriptor = MemberAccessExpression(
            SyntaxKind.SimpleMemberAccessExpression,
            IdentifierName(controlTypeName),
            IdentifierName($"{propertyName}Property"));

        ExpressionSyntax modeEnum = MemberAccessExpression(
            SyntaxKind.SimpleMemberAccessExpression,
            IdentifierName("BindingMode"),
            IdentifierName(binding.Mode));

        string topPropertyName = binding.Path.Split('.')[0];

        if (!string.IsNullOrWhiteSpace(dataType))
        {
            string shortDataType = SimplifyTypeNameInNamespace(dataType, viewNamespace);

            ParameterSyntax sourceParam = Parameter(Identifier("source"))
                .WithType(ParseTypeName(shortDataType));

            LambdaExpressionSyntax getterLambda = ParenthesizedLambdaExpression(
                ParameterList(SingletonSeparatedList(sourceParam)),
                ParseExpression($"source.{binding.Path}"))
                .WithModifiers(TokenList(Token(SyntaxKind.StaticKeyword)));

            ExpressionSyntax setterArg = binding.Mode == "TwoWay"
                ? ParenthesizedLambdaExpression(
                    ParameterList(SeparatedList(
                    [
                        Parameter(Identifier("source")),
                        Parameter(Identifier("value"))
                    ])),
                    AssignmentExpression(
                        SyntaxKind.SimpleAssignmentExpression,
                        ParseExpression($"source.{binding.Path}"),
                        IdentifierName("value")))
                    .WithModifiers(TokenList(Token(SyntaxKind.StaticKeyword)))
                : LiteralExpression(SyntaxKind.NullLiteralExpression);

            InvocationExpressionSyntax bindingCreation = InvocationExpression(
                MemberAccessExpression(
                    SyntaxKind.SimpleMemberAccessExpression,
                    IdentifierName("CompiledBinding"),
                    IdentifierName("Create")))
                .WithArgumentList(ArgumentList(SeparatedList<ArgumentSyntax>(
                [
                    Argument(StringLiteral(topPropertyName)),
                    Argument(getterLambda),
                    Argument(setterArg),
                    Argument(modeEnum)
                ])));

            ExpressionSyntax setBindingTarget = targetExpr is ThisExpressionSyntax
                ? IdentifierName("SetBinding")
                : MemberAccessExpression(
                    SyntaxKind.SimpleMemberAccessExpression,
                    targetExpr,
                    IdentifierName("SetBinding"));

            return ExpressionStatement(
                InvocationExpression(setBindingTarget)
                    .WithArgumentList(ArgumentList(SeparatedList<ArgumentSyntax>(
                    [
                        Argument(propertyDescriptor),
                        Argument(bindingCreation)
                    ]))));
        }

        MemberAccessExpressionSyntax pathBindMethod = MemberAccessExpression(
            SyntaxKind.SimpleMemberAccessExpression,
            IdentifierName("PathBinding"),
            IdentifierName("Bind"));

        return ExpressionStatement(
            InvocationExpression(pathBindMethod)
                .WithArgumentList(ArgumentList(SeparatedList<ArgumentSyntax>(
                [
                    Argument(targetExpr),
                    Argument(propertyDescriptor),
                    Argument(StringLiteral(binding.Path)),
                    Argument(modeEnum)
                ]))));
    }

    private static string SimplifyTypeNameInNamespace(string fullTypeName, string currentNamespace)
    {
        string prefix = currentNamespace + ".";
        if (fullTypeName.StartsWith(prefix, StringComparison.Ordinal))
        {
            return fullTypeName[prefix.Length..];
        }

        return fullTypeName;
    }

    private static LiteralExpressionSyntax StringLiteral(string value)
    {
        return LiteralExpression(SyntaxKind.StringLiteralExpression, Literal(value));
    }
}
