using System.Security.Cryptography;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;
using NativeUI.Media;
using static Microsoft.CodeAnalysis.CSharp.SyntaxFactory;

namespace NativeUI.Xaml.Compiler;

internal sealed record SvgAsset(string Identity, string Content, string Method, ExpressionSyntax? Definition, Diagnostic? Diagnostic);

/// <summary>
/// Compiles declared SVG inputs into typed definition and visual factories.
/// </summary>
internal static class SvgAssetCompiler
{
    private static readonly DiagnosticDescriptor InvalidAsset = new(
        "NXAML010", "Invalid SVG asset", "SVG asset '{0}': {1}", "NativeUI.Xaml", DiagnosticSeverity.Error, true);

    /// <summary>
    /// Reads and validates an SVG compiler input while preserving its declared resource identity.
    /// </summary>
    public static SvgAsset Read(AdditionalText file, AnalyzerConfigOptionsProvider options, CancellationToken cancellationToken)
    {
        string content = file.GetText(cancellationToken)?.ToString() ?? string.Empty;
        options.GetOptions(file).TryGetValue("build_metadata.AdditionalFiles.NativeUIResource", out string? identity);
        string key = string.IsNullOrWhiteSpace(identity)
            ? Path.GetFileName(file.Path)
            : identity.Replace('\\', '/');
        string method = "Create_" + Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(content)))[..24];
        try
        {
            SvgNodeData node = SvgDocumentParser.Parse(content);
            return new SvgAsset(key, content, method, VectorCodeEmitter.Node(node), null);
        }
        catch (Exception exception) when (exception is FormatException or System.Xml.XmlException or ArgumentException or OverflowException)
        {
            Diagnostic diagnostic = Diagnostic.Create(InvalidAsset, Location.None, key, exception.Message);
            return new SvgAsset(key, content, method, null, diagnostic);
        }
    }

    /// <summary>
    /// Emits definition and visual factories per unique SVG content hash without retaining instances.
    /// </summary>
    public static string Emit(IEnumerable<SvgAsset> assets)
    {
        List<MemberDeclarationSyntax> members = [];
        foreach (SvgAsset asset in assets.Where(static asset => asset.Diagnostic is null).DistinctBy(static asset => asset.Method))
        {
            if (asset.Definition is not ExpressionSyntax definition)
            {
                continue;
            }

            string definitionFactoryName = "CreateDefinition_" + asset.Method;
            members.Add(MethodDeclaration(IdentifierName("SvgNode"), Identifier(definitionFactoryName))
                .WithModifiers(TokenList(Token(SyntaxKind.PrivateKeyword), Token(SyntaxKind.StaticKeyword)))
                .WithBody(Block(ReturnStatement(definition))));

            ObjectCreationExpressionSyntax instance = ObjectCreationExpression(IdentifierName("Svg"))
                .WithArgumentList(ArgumentList())
                .WithInitializer(InitializerExpression(SyntaxKind.ObjectInitializerExpression, SingletonSeparatedList<ExpressionSyntax>(
                    AssignmentExpression(SyntaxKind.SimpleAssignmentExpression, IdentifierName("Definition"), InvocationExpression(IdentifierName(definitionFactoryName))))));
            members.Add(MethodDeclaration(IdentifierName("Svg"), Identifier(asset.Method))
                .WithModifiers(TokenList(Token(SyntaxKind.InternalKeyword), Token(SyntaxKind.StaticKeyword)))
                .WithExpressionBody(ArrowExpressionClause(instance))
                .WithSemicolonToken(Token(SyntaxKind.SemicolonToken)));
        }

        ClassDeclarationSyntax assetClass = ClassDeclaration("GeneratedSvgAssets")
            .WithModifiers(TokenList(Token(SyntaxKind.InternalKeyword), Token(SyntaxKind.StaticKeyword)))
            .WithMembers(List(members));
        CompilationUnitSyntax unit = CompilationUnit()
            .WithUsings(List(
            [
                UsingDirective(ParseName("System.Collections.Generic")),
                UsingDirective(ParseName("System.Collections.Immutable")),
                UsingDirective(ParseName("System.Numerics")),
                UsingDirective(ParseName("NativeUI.Controls")),
                UsingDirective(ParseName("NativeUI.Layout")),
                UsingDirective(ParseName("NativeUI.Media"))
            ]))
            .WithMembers(SingletonList<MemberDeclarationSyntax>(
                FileScopedNamespaceDeclaration(ParseName("NativeUI.Generated"))
                    .WithMembers(SingletonList<MemberDeclarationSyntax>(assetClass))))
            .WithLeadingTrivia(TriviaList(
                Comment("// <auto-generated />"),
                Trivia(NullableDirectiveTrivia(Token(SyntaxKind.EnableKeyword), true))));
        return unit.NormalizeWhitespace().ToFullString();
    }

    /// <summary>
    /// Replaces eligible URI assignments with references to generated SVG factories.
    /// </summary>
    public static ValidatedXamlDocument Rewrite(ValidatedXamlDocument document, IEnumerable<SvgAsset> assets, Compilation compilation)
    {
        Dictionary<string, SvgAsset> byIdentity = new(StringComparer.Ordinal);
        foreach (SvgAsset asset in assets.Where(static asset => asset.Diagnostic is null))
        {
            if (byIdentity.TryGetValue(asset.Identity, out SvgAsset? previous) && previous.Content != asset.Content)
            {
                continue;
            }

            byIdentity[asset.Identity] = asset;
        }

        bool HasImageSourceProperty(ValidatedXamlElement element)
        {
            string typeName = element.ControlTypeName.StartsWith("global::", StringComparison.Ordinal)
                ? element.ControlTypeName[8..]
                : element.ControlTypeName.Contains('.') ? element.ControlTypeName : "NativeUI.Controls." + element.ControlTypeName;
            INamedTypeSymbol? type = compilation.GetTypeByMetadataName(typeName);
            INamedTypeSymbol? imageSource = compilation.GetTypeByMetadataName("NativeUI.Media.ImageSource");
            for (INamedTypeSymbol? current = type; current is not null; current = current.BaseType)
            {
                IPropertySymbol? source = current.GetMembers("Source").OfType<IPropertySymbol>().FirstOrDefault();
                if (source is null)
                {
                    continue;
                }

                // A generated factory produces ImageSource, so narrower or unrelated properties cannot accept it.
                return SymbolEqualityComparer.Default.Equals(source.Type, imageSource);
            }

            return false;
        }

        ValidatedXamlProperty RewriteProperty(ValidatedXamlProperty property)
        {
            if (property.PropertyName != "Source" || property.Binding is not null || property.LiteralValue is not string source)
            {
                return property;
            }

            if (!byIdentity.TryGetValue(source.TrimStart('/'), out SvgAsset? asset) && !byIdentity.TryGetValue(source, out asset))
            {
                return property;
            }

            MemberAccessExpressionSyntax factory = MemberAccessExpression(
                SyntaxKind.SimpleMemberAccessExpression,
                IdentifierName("GeneratedSvgAssets"),
                IdentifierName(asset.Method));
            ObjectCreationExpressionSyntax sourceExpression = ObjectCreationExpression(IdentifierName("CompiledSvgSource"))
                .WithArgumentList(ArgumentList(SingletonSeparatedList(Argument(factory))));
            return property with { Kind = XamlPropertyKind.Converted, ConvertedValue = sourceExpression };
        }

        ValidatedXamlElement RewriteElement(ValidatedXamlElement element)
        {
            return element with
            {
                Properties = HasImageSourceProperty(element) ? element.Properties.Select(RewriteProperty).ToArray() : element.Properties,
                Children = element.Children.Select(RewriteElement).ToArray(),
                PropertyElements = element.PropertyElements.Select(property => property with
                {
                    Children = property.Children.Select(RewriteElement).ToArray()
                }).ToArray()
            };
        }

        return document.RootElement is null ? document : document with { RootElement = RewriteElement(document.RootElement) };
    }
}
