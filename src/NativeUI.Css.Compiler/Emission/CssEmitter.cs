using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using static Microsoft.CodeAnalysis.CSharp.SyntaxFactory;

namespace NativeUI.Css.Compiler;

/// <summary>
/// Generates clean, human-readable C# source code from a <see cref="ValidatedCssStylesheet"/>
/// using Roslyn's <see cref="SyntaxFactory"/>.
/// </summary>
public static class CssEmitter
{
    /// <summary>
    /// Builds a Roslyn <see cref="CompilationUnitSyntax"/> for the given <paramref name="stylesheet"/>
    /// in <paramref name="targetNamespace"/> and formats it as C# source text.
    /// </summary>
    public static string Emit(
        ValidatedCssStylesheet stylesheet,
        string targetNamespace,
        Accessibility accessibility = Accessibility.Public)
    {
        ArgumentNullException.ThrowIfNull(stylesheet);
        ArgumentException.ThrowIfNullOrWhiteSpace(targetNamespace);

        CompilationUnitSyntax unit = BuildCompilationUnit(stylesheet, targetNamespace, accessibility);
        return unit.NormalizeWhitespace().ToFullString();
    }

    /// <summary>
    /// Builds the Roslyn <see cref="CompilationUnitSyntax"/> representing the compiled CSS stylesheet class.
    /// </summary>
    public static CompilationUnitSyntax BuildCompilationUnit(
        ValidatedCssStylesheet stylesheet,
        string targetNamespace,
        Accessibility accessibility = Accessibility.Public)
    {
        ArgumentNullException.ThrowIfNull(stylesheet);
        ArgumentException.ThrowIfNullOrWhiteSpace(targetNamespace);

        string safeClassName = SanitizeIdentifier(stylesheet.Id) + "StyleSheet";
        List<MemberDeclarationSyntax> members = [];

        // Emit static readonly ThemeValue<Color> fields for :root color custom properties.
        HashSet<string> emittedTokens = new(StringComparer.Ordinal);
        foreach (ValidatedCssRule rule in stylesheet.Rules)
        {
            if (!rule.IsRoot)
            {
                continue;
            }

            foreach (ValidatedCssDeclaration decl in rule.Declarations)
            {
                if (decl.PropertyName.StartsWith("--", StringComparison.Ordinal) &&
                    decl.ColorLiteral is ParsedCssColor color &&
                    emittedTokens.Add(decl.PropertyName))
                {
                    string tokenFieldName = ToPascalIdentifier(decl.PropertyName[2..]);
                    members.Add(BuildThemeColorField(tokenFieldName, decl.PropertyName, color));
                }
            }
        }

        members.Add(BuildInstanceProperty());
        members.Add(BuildRegisterMethod());
        members.Add(BuildCreateMethod(stylesheet));

        SyntaxKind accessKeyword = accessibility == Accessibility.Internal
            ? SyntaxKind.InternalKeyword
            : SyntaxKind.PublicKeyword;

        ClassDeclarationSyntax classDecl = ClassDeclaration(safeClassName)
            .WithModifiers(TokenList(Token(accessKeyword), Token(SyntaxKind.PartialKeyword)))
            .WithMembers(List(members));

        FileScopedNamespaceDeclarationSyntax namespaceDecl =
            FileScopedNamespaceDeclaration(ParseName(targetNamespace))
                .WithMembers(SingletonList<MemberDeclarationSyntax>(classDecl));

        SyntaxTriviaList leadingTrivia = TriviaList(
            Comment("// <auto-generated />"),
            Trivia(NullableDirectiveTrivia(Token(SyntaxKind.EnableKeyword), true)),
            Trivia(PragmaWarningDirectiveTrivia(
                Token(SyntaxKind.DisableKeyword),
                SeparatedList<ExpressionSyntax>([IdentifierName("CS1591"), IdentifierName("CA2255")]),
                true)));

        return CompilationUnit()
            .WithUsings(List(
            [
                UsingDirective(ParseName("System")),
                UsingDirective(ParseName("System.Collections.Generic")),
                UsingDirective(ParseName("System.Collections.Immutable")),
                UsingDirective(ParseName("System.Runtime.CompilerServices")),
                UsingDirective(ParseName("NativeUI.Core")),
                UsingDirective(ParseName("NativeUI.Css")),
                UsingDirective(ParseName("NativeUI.Media"))
            ]))
            .WithMembers(SingletonList<MemberDeclarationSyntax>(namespaceDecl))
            .WithLeadingTrivia(leadingTrivia);
    }

    private static FieldDeclarationSyntax BuildThemeColorField(
        string fieldName,
        string variableName,
        ParsedCssColor color)
    {
        TypeSyntax fieldType = ParseTypeName("ThemeValue<Color>");
        ImplicitObjectCreationExpressionSyntax initializer = ImplicitObjectCreationExpression()
            .WithArgumentList(ArgumentList(SeparatedList<ArgumentSyntax>(
            [
                Argument(CssValueSyntaxBuilder.StringLiteral(variableName)),
                Argument(CssValueSyntaxBuilder.BuildColorFactoryInvocation(color))
            ])));

        VariableDeclarationSyntax variable = VariableDeclaration(fieldType)
            .WithVariables(SingletonSeparatedList(
                VariableDeclarator(Identifier(fieldName))
                    .WithInitializer(EqualsValueClause(initializer))));

        return FieldDeclaration(variable)
            .WithModifiers(TokenList(
                Token(SyntaxKind.PublicKeyword),
                Token(SyntaxKind.StaticKeyword),
                Token(SyntaxKind.ReadOnlyKeyword)));
    }

    private static PropertyDeclarationSyntax BuildInstanceProperty()
    {
        TypeSyntax sheetType = IdentifierName("CssStyleSheet");
        return PropertyDeclaration(sheetType, Identifier("Instance"))
            .WithModifiers(TokenList(Token(SyntaxKind.PublicKeyword), Token(SyntaxKind.StaticKeyword)))
            .WithAccessorList(AccessorList(SingletonList(
                AccessorDeclaration(SyntaxKind.GetAccessorDeclaration)
                    .WithSemicolonToken(Token(SyntaxKind.SemicolonToken)))))
            .WithInitializer(EqualsValueClause(InvocationExpression(IdentifierName("Create"))))
            .WithSemicolonToken(Token(SyntaxKind.SemicolonToken));
    }

    private static MethodDeclarationSyntax BuildRegisterMethod()
    {
        AttributeListSyntax moduleInitAttr = AttributeList(SingletonSeparatedList(
            Attribute(IdentifierName("ModuleInitializer"))));

        ExpressionStatementSyntax registerCall = ExpressionStatement(
            InvocationExpression(
                MemberAccessExpression(
                    SyntaxKind.SimpleMemberAccessExpression,
                    IdentifierName("CssStyleRegistry"),
                    IdentifierName("Register")))
            .WithArgumentList(ArgumentList(SingletonSeparatedList(
                Argument(IdentifierName("Instance"))))));

        return MethodDeclaration(PredefinedType(Token(SyntaxKind.VoidKeyword)), Identifier("Register"))
            .WithAttributeLists(SingletonList(moduleInitAttr))
            .WithModifiers(TokenList(Token(SyntaxKind.InternalKeyword), Token(SyntaxKind.StaticKeyword)))
            .WithBody(Block(SingletonList<StatementSyntax>(registerCall)));
    }

    private static MethodDeclarationSyntax BuildCreateMethod(ValidatedCssStylesheet stylesheet)
    {
        TypeSyntax ruleType = IdentifierName("CssRule");
        TypeSyntax listType = ParseTypeName("List<CssRule>");

        List<ExpressionSyntax> ruleCreations = [];
        foreach (ValidatedCssRule rule in stylesheet.Rules)
        {
            ruleCreations.Add(BuildRuleCreation(rule, ruleType));
        }

        ObjectCreationExpressionSyntax rulesListCreation = ObjectCreationExpression(listType)
            .WithInitializer(InitializerExpression(
                SyntaxKind.CollectionInitializerExpression,
                SeparatedList(ruleCreations)));

        LocalDeclarationStatementSyntax rulesLocal = LocalDeclarationStatement(
            VariableDeclaration(listType)
                .WithVariables(SingletonSeparatedList(
                    VariableDeclarator(Identifier("rules"))
                        .WithInitializer(EqualsValueClause(rulesListCreation)))));

        ObjectCreationExpressionSyntax sheetCreation = ObjectCreationExpression(IdentifierName("CssStyleSheet"))
            .WithArgumentList(ArgumentList(SeparatedList<ArgumentSyntax>(
            [
                Argument(CssValueSyntaxBuilder.StringLiteral(stylesheet.Id)),
                Argument(CssValueSyntaxBuilder.StringLiteral(stylesheet.BrowserCss)),
                Argument(IdentifierName("rules"))
            ])));

        ReturnStatementSyntax returnStmt = ReturnStatement(sheetCreation);

        return MethodDeclaration(IdentifierName("CssStyleSheet"), Identifier("Create"))
            .WithModifiers(TokenList(Token(SyntaxKind.PrivateKeyword), Token(SyntaxKind.StaticKeyword)))
            .WithBody(Block(rulesLocal, returnStmt));
    }

    private static ObjectCreationExpressionSyntax BuildRuleCreation(ValidatedCssRule rule, TypeSyntax ruleType)
    {
        ExpressionSyntax elementTypeExpr = rule.ElementType is null
            ? LiteralExpression(SyntaxKind.NullLiteralExpression)
            : CssValueSyntaxBuilder.StringLiteral(rule.ElementType);

        ExpressionSyntax classesExpr = BuildClassesExpression(rule.Classes);

        ExpressionSyntax isRootExpr = LiteralExpression(
            rule.IsRoot ? SyntaxKind.TrueLiteralExpression : SyntaxKind.FalseLiteralExpression);

        List<ExpressionSyntax> dictAssigns = [];
        foreach (ValidatedCssDeclaration decl in rule.Declarations)
        {
            AssignmentExpressionSyntax indexerAssign = AssignmentExpression(
                SyntaxKind.SimpleAssignmentExpression,
                ImplicitElementAccess()
                    .WithArgumentList(BracketedArgumentList(SingletonSeparatedList(
                        Argument(CssValueSyntaxBuilder.StringLiteral(decl.PropertyName))))),
                decl.ValueExpression);
            dictAssigns.Add(indexerAssign);
        }

        ObjectCreationExpressionSyntax declarationsDict = ObjectCreationExpression(
            ParseTypeName("Dictionary<string, CssValue>"))
            .WithInitializer(InitializerExpression(
                SyntaxKind.ObjectInitializerExpression,
                SeparatedList(dictAssigns)));

        MemberAccessExpressionSyntax colorSchemeExpr = MemberAccessExpression(
            SyntaxKind.SimpleMemberAccessExpression,
            IdentifierName("CssColorSchemeCondition"),
            IdentifierName(rule.ColorScheme.ToString()));

        List<ArgumentSyntax> arguments =
        [
            Argument(CssValueSyntaxBuilder.StringLiteral(rule.Selector)),
            Argument(elementTypeExpr),
            Argument(classesExpr),
            Argument(isRootExpr),
            Argument(CssValueSyntaxBuilder.IntLiteral(rule.Specificity)),
            Argument(declarationsDict),
            Argument(colorSchemeExpr)
        ];

        if (rule.Ancestors is { Count: > 0 } ancestors)
        {
            arguments.Add(Argument(BuildAncestorsExpression(ancestors)).WithNameColon(NameColon("ancestors")));
        }

        if (rule.RequiredStates is { Count: > 0 } requiredStates)
        {
            arguments.Add(Argument(BuildStatesExpression(requiredStates)).WithNameColon(NameColon("requiredStates")));
        }

        if (rule.PseudoElement != CssParsedPseudoElement.None)
        {
            ExpressionSyntax pseudoElement = MemberAccessExpression(
                SyntaxKind.SimpleMemberAccessExpression,
                IdentifierName("CssPseudoElement"),
                IdentifierName(rule.PseudoElement.ToString()));
            arguments.Add(Argument(pseudoElement).WithNameColon(NameColon("pseudoElement")));
        }

        return ObjectCreationExpression(ruleType)
            .WithArgumentList(ArgumentList(SeparatedList(arguments)));
    }

    private static ExpressionSyntax BuildClassesExpression(IReadOnlyList<string> classes)
    {
        if (classes.Count == 0)
        {
            return MemberAccessExpression(
                SyntaxKind.SimpleMemberAccessExpression,
                ParseTypeName("ImmutableArray<string>"),
                IdentifierName("Empty"));
        }

        return BuildImmutableArrayCreation(classes.Select(CssValueSyntaxBuilder.StringLiteral));
    }

    private static InvocationExpressionSyntax BuildImmutableArrayCreation(IEnumerable<ExpressionSyntax> items)
    {
        return InvocationExpression(
            MemberAccessExpression(
                SyntaxKind.SimpleMemberAccessExpression,
                IdentifierName("ImmutableArray"),
                IdentifierName("Create")))
            .WithArgumentList(ArgumentList(SeparatedList(items.Select(Argument))));
    }

    private static ExpressionSyntax BuildStatesExpression(IReadOnlyList<string> states)
    {
        IEnumerable<ExpressionSyntax> members = (states.Count == 0 ? ["None"] : states).Distinct().Select(static state =>
            (ExpressionSyntax)MemberAccessExpression(
                SyntaxKind.SimpleMemberAccessExpression,
                IdentifierName("ElementStates"),
                IdentifierName(state)));

        return members.Aggregate(static (left, right) =>
            BinaryExpression(SyntaxKind.BitwiseOrExpression, left, right));
    }

    private static ExpressionSyntax BuildAncestorsExpression(IReadOnlyList<CssCompoundSelectorNode> ancestors)
    {
        TypeSyntax compoundType = IdentifierName("CssCompoundSelector");
        IEnumerable<ExpressionSyntax> parts = ancestors.Select(ancestor =>
        {
            ExpressionSyntax elementType = ancestor.ElementType is null
                ? LiteralExpression(SyntaxKind.NullLiteralExpression)
                : CssValueSyntaxBuilder.StringLiteral(ancestor.ElementType);

            return (ExpressionSyntax)ObjectCreationExpression(compoundType)
                .WithArgumentList(ArgumentList(SeparatedList<ArgumentSyntax>(
                [
                    Argument(elementType),
                    Argument(BuildClassesExpression(ancestor.Classes)),
                    Argument(BuildStatesExpression(ancestor.RequiredStates))
                ])));
        });

        return BuildImmutableArrayCreation(parts);
    }

    private static string SanitizeIdentifier(string raw)
    {
        StringBuilder sb = new();
        foreach (char c in raw)
        {
            if (char.IsLetterOrDigit(c) || c == '_')
            {
                sb.Append(c);
            }
        }

        return sb.Length > 0 ? sb.ToString() : "Generated";
    }

    private static string ToPascalIdentifier(string kebab)
    {
        StringBuilder sb = new();
        bool capitalizeNext = true;
        foreach (char c in kebab)
        {
            if (c == '-' || c == '_')
            {
                capitalizeNext = true;
            }
            else if (char.IsLetterOrDigit(c))
            {
                sb.Append(capitalizeNext ? char.ToUpperInvariant(c) : c);
                capitalizeNext = false;
            }
        }

        return sb.Length > 0 ? sb.ToString() : "CustomToken";
    }
}
