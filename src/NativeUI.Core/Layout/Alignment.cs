namespace NativeUI.Layout;

/// <summary>
/// Identifies a position along an axis.
/// </summary>
public enum Alignment
{
    /// <summary>
    /// The left or top end of the axis.
    /// </summary>
    Start,

    /// <summary>
    /// The middle of the axis.
    /// </summary>
    Center,

    /// <summary>
    /// The right or bottom end of the axis.
    /// </summary>
    End
}
