namespace NativeUI.Media;

/// <summary>Shared immutable brushes for named colors.</summary>
public static class Brushes
{
    /// <summary>Gets the Transparent brush.</summary>
    public static SolidColorBrush Transparent { get; } = new(Colors.Transparent);

    /// <summary>Gets the Black brush.</summary>
    public static SolidColorBrush Black { get; } = new(Colors.Black);

    /// <summary>Gets the White brush.</summary>
    public static SolidColorBrush White { get; } = new(Colors.White);

    /// <summary>Gets the Blue brush.</summary>
    public static SolidColorBrush Blue { get; } = new(Colors.Blue);

    /// <summary>Gets the Indigo brush.</summary>
    public static SolidColorBrush Indigo { get; } = new(Colors.Indigo);

    /// <summary>Gets the Green brush.</summary>
    public static SolidColorBrush Green { get; } = new(Colors.Green);

    /// <summary>Gets the Red brush.</summary>
    public static SolidColorBrush Red { get; } = new(Colors.Red);
}
