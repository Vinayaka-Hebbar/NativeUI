namespace NativeUI.Media;

/// <summary>
/// Specifies horizontal alignment for text content.
/// </summary>
public enum TextAlign
{
    /// <summary>
    /// Aligns text to the leading/left edge.
    /// </summary>
    Left,

    /// <summary>
    /// Centers text horizontally.
    /// </summary>
    Center,

    /// <summary>
    /// Aligns text to the trailing/right edge.
    /// </summary>
    Right
}
