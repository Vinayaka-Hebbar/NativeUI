namespace NativeUI.Media;

/// <summary>Defines supported Alignment values in an immutable SVG definition.</summary>
public enum SvgAlignment
{
    /// <summary>Uses None semantics.</summary>
    None,
    /// <summary>Uses XMinYMin semantics.</summary>
    XMinYMin,
    /// <summary>Uses XMidYMin semantics.</summary>
    XMidYMin,
    /// <summary>Uses XMaxYMin semantics.</summary>
    XMaxYMin,
    /// <summary>Uses XMinYMid semantics.</summary>
    XMinYMid,
    /// <summary>Uses XMidYMid semantics.</summary>
    XMidYMid,
    /// <summary>Uses XMaxYMid semantics.</summary>
    XMaxYMid,
    /// <summary>Uses XMinYMax semantics.</summary>
    XMinYMax,
    /// <summary>Uses XMidYMax semantics.</summary>
    XMidYMax,
    /// <summary>Uses XMaxYMax semantics.</summary>
    XMaxYMax
}
