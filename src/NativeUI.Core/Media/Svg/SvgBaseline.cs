namespace NativeUI.Media;

/// <summary>Defines supported Baseline values in an immutable SVG definition.</summary>
public enum SvgBaseline
{
    /// <summary>Uses Auto semantics.</summary>
    Auto,
    /// <summary>Uses Alphabetic semantics.</summary>
    Alphabetic,
    /// <summary>Uses Middle semantics.</summary>
    Middle,
    /// <summary>Uses Central semantics.</summary>
    Central,
    /// <summary>Uses Hanging semantics.</summary>
    Hanging,
    /// <summary>Uses TextBeforeEdge semantics.</summary>
    TextBeforeEdge,
    /// <summary>Uses TextAfterEdge semantics.</summary>
    TextAfterEdge,
    /// <summary>Uses Ideographic semantics.</summary>
    Ideographic,
    /// <summary>Uses Mathematical semantics.</summary>
    Mathematical
}
