namespace NativeUI.Media;

/// <summary>Specifies stretch behavior for vector and image content.</summary>
public enum Stretch
{
    /// <summary>Uses None behavior.</summary>
    None,
    /// <summary>Uses Fill behavior.</summary>
    Fill,
    /// <summary>Uses Uniform behavior.</summary>
    Uniform,
    /// <summary>Uses UniformToFill behavior.</summary>
    UniformToFill
}
