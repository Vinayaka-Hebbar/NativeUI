namespace NativeUI.Media;

/// <summary>
/// Specifies the typographic weight of rendered text.
/// </summary>
public enum FontWeight
{
    /// <summary>
    /// Thin font weight (100).
    /// </summary>
    Thin = 100,

    /// <summary>
    /// Light font weight (300).
    /// </summary>
    Light = 300,

    /// <summary>
    /// Normal / regular font weight (400).
    /// </summary>
    Normal = 400,

    /// <summary>
    /// Medium font weight (500).
    /// </summary>
    Medium = 500,

    /// <summary>
    /// Semi-bold font weight (600).
    /// </summary>
    SemiBold = 600,

    /// <summary>
    /// Bold font weight (700).
    /// </summary>
    Bold = 700,

    /// <summary>
    /// Extra-bold font weight (800).
    /// </summary>
    ExtraBold = 800,

    /// <summary>
    /// Black / heavy font weight (900).
    /// </summary>
    Black = 900
}
