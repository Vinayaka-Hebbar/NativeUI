import { dotnet } from "../../_framework/dotnet.js";
import { ButtonElement } from "./elements/nativeui-button.js";
import { InputElement } from "./elements/nativeui-input.js";
import { TextElement } from "./elements/nativeui-text.js";
import { SelectElement } from "./elements/nativeui-select.js";
import { DomInterop } from "./nativeui-dom.js";
import { CanvasElement, CanvasContext2D } from "./elements/nativeui-canvas.js";
import { ImageElement } from "./elements/nativeui-image.js";
import { NativeUIRoot } from "./nativeui-root.js";
import { PortalElement } from "./elements/nativeui-portal.js";
import { ContextMenuElement } from "./elements/nativeui-context-menu.js";
import { DialogElement } from "./elements/nativeui-dialog.js";
import { FormElement } from "./elements/nativeui-form.js";
import { LabelElement } from "./elements/nativeui-label.js";
import { StyleSheetInterop } from "./nativeui-styles.js";
import { ThemeInterop } from "./nativeui-theme.js";

const runtime = await dotnet.create();
runtime.setModuleImports("nativeui-dom", DomInterop);
runtime.setModuleImports("nativeui-button", ButtonElement);
runtime.setModuleImports("nativeui-input", InputElement);
runtime.setModuleImports("nativeui-select", SelectElement);
runtime.setModuleImports("nativeui-text", TextElement);
runtime.setModuleImports("nativeui-canvas", CanvasElement);
runtime.setModuleImports("nativeui-canvas-context-2d", CanvasContext2D);
runtime.setModuleImports("nativeui-image", ImageElement);
runtime.setModuleImports("nativeui-root", NativeUIRoot);
runtime.setModuleImports("nativeui-portal", PortalElement);
runtime.setModuleImports("nativeui-dialog", DialogElement);
runtime.setModuleImports("nativeui-context-menu", ContextMenuElement);
runtime.setModuleImports("nativeui-form", FormElement);
runtime.setModuleImports("nativeui-label", LabelElement);
runtime.setModuleImports("nativeui-styles", StyleSheetInterop);
runtime.setModuleImports("nativeui-theme", ThemeInterop);
await dotnet.run();
